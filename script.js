function openDocument(data) {

    documentTitle.textContent =
        data.title;

    documentNumber.textContent =
        data.number;

    documentContent.textContent =
        data.text;

    documentContent.scrollTop = 0;


    documentOverlay.classList.add(
        "active"
    );
}


